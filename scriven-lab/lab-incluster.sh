#!/usr/bin/env bash
# Run scriven inside the lab, the way it runs in production: the watcher as a
# Deployment and the nightly sweep as a CronJob, in namespace scriven-system on
# prod-sim, watching both prod-sim and dev-sim with their read-only identities.
#
#   ./lab-incluster.sh          build the image, deploy, point audit webhooks at it
#   ./lab-incluster.sh --down   remove it and point audit webhooks back at the host
#
# Needs ./lab-up.sh and ./lab-seed.sh first. Builds the image from the repo root.
set -euo pipefail
cd "$(dirname "$0")"
export MSYS_NO_PATHCONV=1
source .env
ctx=k3d-prod-sim
out=.lab/incluster

if [[ "${1:-}" == "--down" ]]; then
  kubectl --context "$ctx" delete namespace scriven-system --ignore-not-found
  ./lab-audit-target.sh host
  exit 0
fi

echo "==> Audit webhooks -> in-cluster scriven (restarts the API servers, so do it before reading container IPs)"
./lab-audit-target.sh cluster

echo "==> Image"
docker build -q -t scriven:dev .. >/dev/null
k3d image import scriven:dev -c prod-sim >/dev/null 2>&1
echo "   scriven:dev imported into prod-sim"

echo "==> Kubeconfigs for the read-only identities, using in-network API addresses"
mkdir -p "$out"
for c in prod-sim dev-sim; do
  cp ".lab/$c.kubeconfig" "$out/$c.kubeconfig"
  kubectl config --kubeconfig "$out/$c.kubeconfig" set-cluster "$c" --server "https://k3d-$c-serverlb:6443" >/dev/null
done

echo "==> Vault: webhook address as seen from inside the cluster"
docker exec -e VAULT_ADDR=http://127.0.0.1:8200 -e VAULT_TOKEN="${VAULT_DEV_TOKEN:-root}" vault \
  vault kv put secret/scriven/teams-webhook-incluster value="http://webhook-catcher:8080/teams" >/dev/null

echo "==> Settings"
cat > "$out/scriven.yaml" <<'EOF'
# Lab settings for scriven running in prod-sim (namespace scriven-system).
version: 1
scope:
  pilot: rancher/prod-sim
  targets:
    - platform: rancher
      id: prod-sim
      env: prod
      owner: platform-team
      kubeconfig: /etc/scriven/kubeconfigs/prod-sim.kubeconfig
    - platform: rancher
      id: dev-sim
      env: dev
      owner: platform-team
      kubeconfig: /etc/scriven/kubeconfigs/dev-sim.kubeconfig
EOF
# The AWS sample, when the Moto emulator is running (./lab-aws.sh).
aws_lab=""
if [[ "$(docker inspect -f '{{.State.Running}}' moto 2>/dev/null)" == "true" ]]; then
  aws_lab=moto
  cat >> "$out/scriven.yaml" <<'EOF'
    - platform: aws
      id: shop-lab
      env: dev
      owner: payments-team
      region: eu-west-1
      access_key_id: vault://scriven/aws-readonly#access_key_id
      secret_access_key: vault://scriven/aws-readonly#secret_access_key
      endpoint: http://moto:5000
EOF
fi
cat >> "$out/scriven.yaml" <<'EOF'
library:
  provider: gitea
  url: http://gitea:3000/scriven/iac-library.git
  username: scriven
  credentials: vault://scriven/git-token
notify:
  channels: [teams, email]
  teams_webhook: vault://scriven/teams-webhook-incluster
  email_to: [platform-team@lab.local]
  smtp:
    host: mailpit
    port: 1025
    from: scriven@lab.local
merge_policy:
  default: {approvals: 1}
  dev: {auto_merge: true, branch: dev-library}  # main needs approvals, so dev merges into its own branch
  prod: {approvals: 2}
vault:
  addr: http://vault:8200
  mount: secret
watch:
  debounce: 10s
  audit_listen: ":8099"
EOF

# Pods can't resolve the lab's Docker container names, so pin them with hostAliases.
ip() { docker inspect -f '{{(index .NetworkSettings.Networks "scriven-lab").IPAddress}}' "$1"; }
aliases=""
for n in gitea vault mailpit webhook-catcher k3d-prod-sim-serverlb k3d-dev-sim-serverlb $aws_lab; do
  aliases+="          - ip: \"$(ip "$n")\"
            hostnames: [\"$n\"]
"
done

cat > "$out/kustomization.yaml" <<EOF
# Generated by lab-incluster.sh: the lab overlay on top of deploy/.
apiVersion: kustomize.config.k8s.io/v1beta1
kind: Kustomization
resources:
  - ../../../deploy
images:
  - name: scriven
    newName: scriven
    newTag: dev
configMapGenerator:
  - name: scriven-config
    namespace: scriven-system
    files: [scriven.yaml]
secretGenerator:
  - name: scriven-kubeconfigs
    namespace: scriven-system
    files: [prod-sim.kubeconfig, dev-sim.kubeconfig]
  - name: scriven-env
    namespace: scriven-system
    literals: [VAULT_TOKEN=${VAULT_DEV_TOKEN:-root}]
patches:
  - target: { kind: Deployment, name: scriven-watch }
    patch: |-
      apiVersion: apps/v1
      kind: Deployment
      metadata: { name: scriven-watch }
      spec:
        template:
          spec:
            hostAliases:
$(printf '%s' "$aliases" | sed 's/^/  /')
  - target: { kind: CronJob, name: scriven-sweep }
    patch: |-
      apiVersion: batch/v1
      kind: CronJob
      metadata: { name: scriven-sweep }
      spec:
        jobTemplate:
          spec:
            template:
              spec:
                hostAliases:
$(printf '%s' "$aliases" | sed 's/^/      /')
  # API servers reach the audit webhook through a NodePort.
  - target: { kind: Service, name: scriven-audit }
    patch: |-
      - { op: add, path: /spec/type, value: NodePort }
      - { op: add, path: /spec/ports/0/nodePort, value: 30099 }
EOF

echo "==> Deploy"
kubectl --context "$ctx" apply -k "$out" | sed 's/^/   /'
# Same tag, possibly a rebuilt image: restart so the pod runs what was just imported.
kubectl --context "$ctx" -n scriven-system rollout restart deploy/scriven-watch >/dev/null
kubectl --context "$ctx" -n scriven-system rollout status deploy/scriven-watch --timeout=180s | sed 's/^/   /'


cat <<EOF

scriven is running in prod-sim, namespace scriven-system.
  logs      kubectl --context $ctx -n scriven-system logs -f deploy/scriven-watch
  sweep now kubectl --context $ctx -n scriven-system create job --from=cronjob/scriven-sweep sweep-now
  remove    ./lab-incluster.sh --down
EOF
