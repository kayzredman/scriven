const awsProvider = "hashicorp/aws"

const awsHeader = "Generated by scriven from the live AWS account and verified with a zero-diff plan.\n" +
	"Change the account through a reviewed PR here, or re-capture: hand edits that do not match\n" +
	"the account show up as drift."

// ConnectAWS logs in to an AWS target with the credentials its settings name.
func ConnectAWS(ctx context.Context, t config.Target, resolve func(string) (string, error)) (*awscloud.Client, error) {
	o := awscloud.Options{Region: t.Region, Profile: t.Profile, Endpoint: t.Endpoint}
	if t.AccessKeyID != "" {
		if resolve == nil {
			return nil, fmt.Errorf("%s: no secret store to resolve access_key_id", t.Key())
		}
		var err error
		if o.AccessKeyID, err = resolve(t.AccessKeyID); err != nil {
			return nil, err
		}
		if o.SecretAccessKey, err = resolve(t.SecretAccessKey); err != nil {
			return nil, err
		}
	}
	return awscloud.Connect(ctx, o)
}

// runAWS is a full capture of one AWS account and region: the same steps as a
// cluster capture, with AWS's own discovery, clean-up rules and references.
func runAWS(ctx context.Context, t config.Target, opt Options) (*Result, error) {
	say := opt.Progress
	if say == nil {
		say = func(int, string) {}
	}
	say(1, "connecting to "+t.Key())
	c, err := ConnectAWS(ctx, t, opt.Secrets)
	if err != nil {
		return nil, err
	}
	bad, method, err := c.ReadOnlyViolations(ctx)
	if err != nil {
		return nil, err
	}
	if len(bad) > 0 {
		return nil, fmt.Errorf("refusing to capture: identity %s is not read-only:\n  - %s", c.ARN, joinLines(bad))
	}
	say(1, fmt.Sprintf("identity %s is read-only (checked by %s)", c.ARN, method))

	say(1, "listing resources")
	inv, err := c.Discover(ctx)
	if err != nil {
		return nil, err
	}
	say(1, fmt.Sprintf("found %d resources to capture, %d left out (see catalog.yaml)", len(inv.Items), len(inv.Skipped)))
	if len(inv.Items) == 0 {
		return nil, fmt.Errorf("nothing to capture in %s", t.Key())
	}

	tfv, err := TerraformVersion(ctx)
	if err != nil {
		return nil, err
	}
	work, err := os.MkdirTemp("", "scriven-capture-")
	if err != nil {
		return nil, err
	}
	if opt.KeepWorkdir {
		defer say(5, "work dir kept at "+work)
	} else {
		defer os.RemoveAll(work)
	}
	write := func(name string, b []byte) error { return os.WriteFile(filepath.Join(work, name), b, 0o644) }

	// 2. Import blocks
	say(2, fmt.Sprintf("writing %d import blocks", len(inv.Items)))
	byAddr := awsAddresses(inv.Items)
	files := map[string][]byte{
		"imports.tf":   awsImports(byAddr),
		"providers.tf": awsProviderTF(false),
		"variables.tf": awsVariablesTF(c.Region),
		"versions.tf":  versionsTF(tfv, awsProvider, ""),
	}
	for n, b := range files {
		if err := write(n, b); err != nil {
			return nil, err
		}
	}
	if o := c.EmulatorOverride(); o != nil {
		if err := write("scriven_override.tf", o); err != nil {
			return nil, err
		}
	}
	runner := &tf{dir: work, env: c.Env()}
	if err := runner.initCached(ctx, awsProvider); err != nil {
		return nil, err
	}
	providers := lockedProviders(work)
	files["versions.tf"] = versionsTF(tfv, awsProvider, providers[awsProvider])
	if err := write("versions.tf", files["versions.tf"]); err != nil {
		return nil, err
	}
	if lock, err := os.ReadFile(filepath.Join(work, ".terraform.lock.hcl")); err == nil {
		files[".terraform.lock.hcl"] = lock
	}

	// 3. Generate HCL
	say(3, fmt.Sprintf("terraform %s, %s %s: plan -generate-config-out", tfv, awsProvider, providers[awsProvider]))
	genOut, genErr := runner.run(ctx, "plan", "-input=false", "-lock=false", "-no-color", "-generate-config-out=generated.tf")
	raw, err := os.ReadFile(filepath.Join(work, "generated.tf"))
	if err != nil {
		if genErr != nil {
			return nil, genErr
		}
		return nil, fmt.Errorf("terraform did not generate any config: %w", err)
	}

	// 4. Clean up
	main, st, err := cleanAWS(raw, byAddr, awsWhere{account: c.Account, region: c.Region})
	if err != nil {
		return nil, err
	}
	if err := os.Remove(filepath.Join(work, "generated.tf")); err != nil {
		return nil, err
	}
	res, err := SplitBlocks(main, "resource")
	if err != nil {
		return nil, err
	}
	// A resource Terraform could not import has no generated block. Leave it
	// out, and say so, rather than fail the whole capture.
	skipped := inv.Skipped
	for addr, it := range byAddr {
		if _, ok := res[addr]; !ok {
			skipped = append(skipped, awscloud.Skipped{Kind: it.Type, Name: it.ID,
				Reason: "terraform could not import it: " + importFailure(genOut, addr, it.ID)})
			delete(byAddr, addr)
		}
	}
	if len(res) == 0 {
		if genErr != nil {
			return nil, genErr
		}
		return nil, fmt.Errorf("terraform imported none of the %d resources", len(inv.Items))
	}
	files["imports.tf"] = awsImports(byAddr)
	files["main.tf"] = main
	files["providers.tf"] = awsProviderTF(strings.Contains(string(main), "data.aws_caller_identity.current"))
	for _, n := range []string{"imports.tf", "main.tf", "providers.tf"} {
		if err := write(n, files[n]); err != nil {
			return nil, err
		}
	}
	say(4, fmt.Sprintf("removed %d empty, zero or AWS-assigned values; replaced %d literal IDs with references "+
		"and %d account, region or ARN parts of strings with expressions", st.removed, st.linked, st.templated))

	// 5. Verify
	say(5, "terraform plan against the live account (read-only)")
	plan, err := runner.planZeroDiff(ctx, awsNote)
	if err != nil {
		return nil, err
	}

	cat := Catalog{
		Owner:         t.Owner,
		CapturedAt:    time.Now().UTC().Format(time.RFC3339),
		Source:        CatalogSource{Platform: t.Platform, ID: t.ID, Env: t.Env, Server: c.Where(), Identity: c.ARN, ReadOnlyCheck: method},
		Tool:          "scriven " + ToolVersion,
		Terraform:     tfv,
		Providers:     providers,
		ResourceCount: len(res),
		ZeroDiff:      plan.ZeroDiff(),
		ZeroDiffNotes: providerOnlyNotes(plan.ProviderOnly),
		Uncaptured: Uncaptured{
			UnreadableKinds: inv.Unreadable,
			Note: "This capture covers these resource types only: " + strings.Join(awscloud.Covered, ", ") +
				". Anything else in the account is not captured yet.",
		},
	}
	sort.Slice(skipped, func(i, j int) bool {
		return skipped[i].Kind+skipped[i].Name < skipped[j].Kind+skipped[j].Name
	})
	for _, s := range skipped {
		cat.Uncaptured.Skipped = append(cat.Uncaptured.Skipped, Skipped{Kind: s.Kind, Name: s.Name, Reason: s.Reason})
	}
	cy, err := yaml.Marshal(cat)
	if err != nil {
		return nil, err
	}
	files["catalog.yaml"] = cy
	return &Result{Target: t, Dir: LibraryDir(t), Files: files, Catalog: cat, Plan: plan}, nil
}

// importFailure finds Terraform's reason for not importing id, for catalog.yaml.
func importFailure(out, addr, id string) string {
	for i, chunk := range strings.Split(out, "\nError: ") {
		if i == 0 {
			continue // everything before the first error
		}
		if strings.Contains(chunk, `"`+addr+`"`) || strings.Contains(chunk, `"`+id+`"`) || strings.Contains(chunk, " "+addr+",") {
			first, _, _ := strings.Cut(chunk, "\n")
			return strings.TrimSpace(first)
		}
	}
	return "no reason given; run `scriven capture --keep-workdir` and plan there"
}

// awsAddresses gives every item a unique Terraform address.
func awsAddresses(items []awscloud.Item) map[string]awscloud.Item {
	out := map[string]awscloud.Item{}
	for _, it := range items {
		name := identName(it.Name)
		addr := it.Type + "." + name
		for n := 2; ; n++ {
			if _, taken := out[addr]; !taken {
				break
			}
			addr = fmt.Sprintf("%s.%s_%d", it.Type, name, n)
		}
		out[addr] = it
	}
	return out
}

func awsImports(byAddr map[string]awscloud.Item) []byte {
	f := hclwrite.NewEmptyFile()
	b := f.Body()
	for addr, it := range byAddr {
		typ, name, _ := strings.Cut(addr, ".")
		blk := b.AppendNewBlock("import", nil).Body()
		blk.SetAttributeTraversal("to", hcl.Traversal{hcl.TraverseRoot{Name: typ}, hcl.TraverseAttr{Name: name}})
		blk.SetAttributeValue("id", cty.StringVal(it.ID))
		b.AppendNewline()
	}
	imps, _ := SplitBlocks(f.Bytes(), "import")
	return joinBlocks(imps, "")
}

// The library holds no credentials and no endpoint: whoever runs this code
// supplies them the usual AWS way (environment, profile, role).
//
// withAccount adds the caller-identity data source that main.tf uses where a
// string held this account's ID (policies, ARNs, bucket names), so the code
// works unchanged in another account.
func awsProviderTF(withAccount bool) []byte {
	f := hclwrite.NewEmptyFile()
	p := f.Body().AppendNewBlock("provider", []string{"aws"}).Body()
	p.SetAttributeTraversal("region", hcl.Traversal{hcl.TraverseRoot{Name: "var"}, hcl.TraverseAttr{Name: "aws_region"}})
	if withAccount {
		f.Body().AppendNewline()
		f.Body().AppendNewBlock("data", []string{"aws_caller_identity", "current"})
	}
	return hclwrite.Format(f.Bytes())
}

func awsVariablesTF(region string) []byte {
	f := hclwrite.NewEmptyFile()
	v := f.Body().AppendNewBlock("variable", []string{"aws_region"}).Body()
	v.SetAttributeTraversal("type", hcl.Traversal{hcl.TraverseRoot{Name: "string"}})
	v.SetAttributeValue("description", cty.StringVal("Region these resources live in"))
	v.SetAttributeValue("default", cty.StringVal(region))
	return hclwrite.Format(f.Bytes())
}
