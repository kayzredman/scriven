package capture

import (
	"fmt"
	"os"
	"path/filepath"
	"sort"
	"strings"

	"github.com/hashicorp/hcl/v2"
	"github.com/hashicorp/hcl/v2/hclwrite"
)

const mainHeader = "Generated by scriven from the live cluster and verified with a zero-diff plan.\n" +
	"Change the cluster through a reviewed PR here, or re-capture: hand edits that do not match\n" +
	"the cluster show up as drift."

// AddressOf is the Terraform address scriven uses for an object, e.g.
// "kubernetes_deployment_v1.shop_web". Empty when the kind is not captured.
func AddressOf(d Discovered) string {
	typ, ok := typedResourceFor(d)
	if !ok {
		return ""
	}
	return typ + "." + addrName(d)
}

// SplitBlocks returns each "resource" or "import" block in src, formatted on
// its own, keyed by Terraform address.
func SplitBlocks(src []byte, kind string) (map[string][]byte, error) {
	f, diags := hclwrite.ParseConfig(src, "in.tf", hcl.InitialPos)
	if diags.HasErrors() {
		return nil, fmt.Errorf("parsing %s blocks: %s", kind, diags.Error())
	}
	out := map[string][]byte{}
	for _, b := range f.Body().Blocks() {
		if b.Type() != kind {
			continue
		}
		addr := blockAddress(b)
		if addr == "" {
			continue
		}
		one := hclwrite.NewEmptyFile()
		one.Body().AppendBlock(b)
		out[addr] = hclwrite.Format(trimComments(one.Bytes()))
	}
	return out, nil
}

func blockAddress(b *hclwrite.Block) string {
	switch b.Type() {
	case "resource":
		if l := b.Labels(); len(l) == 2 {
			return l[0] + "." + l[1]
		}
	case "import":
		if a := b.Body().GetAttribute("to"); a != nil {
			return strings.TrimSpace(string(a.Expr().BuildTokens(nil).Bytes()))
		}
	}
	return ""
}

func trimComments(b []byte) []byte {
	var keep []string
	for _, l := range strings.Split(string(b), "\n") {
		if !strings.HasPrefix(strings.TrimSpace(l), "#") {
			keep = append(keep, l)
		}
	}
	return []byte(strings.Join(keep, "\n"))
}

// Change is one resource to add, replace or remove in a library directory.
type Change struct {
	Address  string
	Resource []byte // nil to remove
	Import   []byte // nil to remove
}

// ApplyChanges edits main.tf and imports.tf in dir, keeping blocks sorted by
// address so the result is identical to what a full capture would write.
// It returns the previous resource block of each address ("" if new).
func ApplyChanges(dir string, changes []Change) (map[string]string, error) {
	mainPath, impPath := filepath.Join(dir, "main.tf"), filepath.Join(dir, "imports.tf")
	mainSrc, err := os.ReadFile(mainPath)
	if err != nil {
		return nil, err
	}
	impSrc, err := os.ReadFile(impPath)
	if err != nil {
		return nil, err
	}
	res, err := SplitBlocks(mainSrc, "resource")
	if err != nil {
		return nil, err
	}
	imp, err := SplitBlocks(impSrc, "import")
	if err != nil {
		return nil, err
	}
	before := map[string]string{}
	for _, c := range changes {
		before[c.Address] = string(res[c.Address])
		if c.Resource == nil {
			delete(res, c.Address)
			delete(imp, c.Address)
			continue
		}
		res[c.Address] = c.Resource
		imp[c.Address] = c.Import
	}
	if err := os.WriteFile(mainPath, joinBlocks(res, mainHeader), 0o644); err != nil {
		return nil, err
	}
	return before, os.WriteFile(impPath, joinBlocks(imp, ""), 0o644)
}

// joinBlocks writes blocks in address order. The order matches cleanGenerated,
// which sorts by the block's labels (type, then name) — the same as by address.
func joinBlocks(blocks map[string][]byte, header string) []byte {
	keys := make([]string, 0, len(blocks))
	for k := range blocks {
		keys = append(keys, k)
	}
	sort.Strings(keys)
	var sb strings.Builder
	if header != "" {
		for _, l := range strings.Split(header, "\n") {
			sb.WriteString("# " + l + "\n")
		}
	}
	for i, k := range keys {
		if i > 0 || header != "" {
			sb.WriteString("\n")
		}
		sb.WriteString(strings.TrimSpace(string(blocks[k])) + "\n")
	}
	return hclwrite.Format([]byte(sb.String()))
}
